"""Сборка текста подсказки для языковой модели.

Подсказка собирается из двух частей.

Первая часть постоянна и одинакова для всех запросов: правила формирования
запроса и компактный указатель всех витрин. Сервер вывода vLLM сохраняет
результат её обработки и повторно использует при следующих обращениях.
Приём называется кэшированием префикса и снимает основную долю затрат
на обработку подсказки.

Вторая часть зависит от вопроса: подробные описания отобранных витрин
и примеры пар "вопрос и эталонный запрос".

Порядок частей менять нельзя. Кэширование работает только для совпадающего
начала текста, поэтому переменная часть обязана располагаться после постоянной.
"""

from __future__ import annotations

from datetime import date

from dwh_copilot.catalog import Catalog

# Правила, по которым модель формирует запрос. Изменение этого текста
# приравнивается к изменению кода: правка проходит проверку набором
# бизнес-вопросов, и при снижении доли верных ответов не принимается.
RULES = """\
Ты формируешь запросы на языке T-SQL к корпоративному хранилищу данных
на Microsoft SQL Server. Отвечай только запросом, без пояснений и без обрамления
разметкой.

Правила:

1. Обращайся только к витринам из перечня ниже. Обращение к любому другому
   объекту базы данных запрещено и будет отклонено.
2. Используй синтаксис T-SQL. Ограничение числа строк задаётся конструкцией TOP,
   а не LIMIT.
3. Всегда указывай условие соединения ON. Соединение без условия отклоняется.
4. Не используй SELECT со звёздочкой. Перечисляй нужные колонки явно.
5. Агрегируй данные. Запрос, возвращающий сотни тысяч строк, будет отклонён
   по оценке стоимости выполнения.
6. Относительные периоды вида "последние три месяца" отсчитывай от даты
   актуальности данных, указанной ниже, а не от сегодняшней даты.
7. Если ответить на вопрос по доступным витринам нельзя, верни строку
   NO_ANSWER и через двоеточие краткую причину на русском языке. Отказ является
   допустимым и правильным ответом. Не придумывай названия таблиц и колонок.
8. Если формулировка вопроса допускает несколько толкований, выбери вариант,
   указанный в разделе "Трактовки по умолчанию" описания витрины.
"""


def build_system_prompt(catalog: Catalog, data_as_of: str, today: str) -> str:
    """Формирует постоянную часть подсказки.

    Аргументы:
        catalog: каталог витрин.
        data_as_of: дата актуальности данных в хранилище.
        today: текущая дата.

    Возвращает:
        Текст, одинаковый для всех запросов в пределах суток. Именно эта часть
        сохраняется механизмом кэширования префикса на сервере вывода.
    """
    return (
        f"{RULES}\n"
        f"Сегодняшняя дата: {today}\n"
        f"Данные в хранилище загружены по: {data_as_of}\n\n"
        f"{catalog.render_index()}\n"
    )


def build_user_prompt(
    question: str,
    catalog: Catalog,
    view_names: list[str],
    examples: list[tuple[str, str]],
) -> str:
    """Формирует переменную часть подсказки.

    Аргументы:
        question: вопрос пользователя.
        catalog: каталог витрин.
        view_names: витрины, отобранные под этот вопрос.
        examples: пары "вопрос и эталонный запрос", отобранные по близости.
            Это самый действенный способ поднять качество: модель перенимает
            принятый в организации способ считать периоды и называть показатели.

    Возвращает:
        Текст с подробными описаниями витрин, примерами и самим вопросом.
    """
    blocks = ["Подробное описание витрин, подходящих к вопросу:", ""]
    blocks.append(catalog.render_details(view_names))

    if examples:
        blocks.extend(["", "Примеры запросов, принятых в организации:", ""])
        for example_question, example_sql in examples:
            blocks.append(f"Вопрос: {example_question}")
            blocks.append(f"Запрос:\n{example_sql.strip()}")
            blocks.append("")

    blocks.extend(["Вопрос пользователя:", question])
    return "\n".join(blocks)


def build_repair_prompt(sql: str, error: str) -> str:
    """Формирует сообщение об ошибке для повторной попытки.

    Текст ошибки передаётся модели, а не пользователю. Модель является
    единственным участником, способным исправить собственный запрос.
    Пользователю показывается обобщённая формулировка и код обращения.
    """
    return (
        "Предыдущий запрос отклонён.\n\n"
        f"Запрос:\n{sql}\n\n"
        f"Причина: {error}\n\n"
        "Исправь запрос с учётом причины. Ответь только исправленным запросом."
    )


def build_summary_prompt(question: str, table_markdown: str) -> str:
    """Формирует задание на текстовый вывод по готовой таблице.

    Модель не имеет доступа к базе данных на этом шаге и работает только
    с переданными строками. Требование опираться исключительно на них
    задано явно, чтобы исключить домысливание отсутствующих цифр.
    """
    return (
        "Ниже приведён результат запроса к хранилищу.\n\n"
        f"Вопрос пользователя: {question}\n\n"
        f"Данные:\n{table_markdown}\n\n"
        "Сформулируй краткий вывод на русском языке, от двух до четырёх "
        "предложений. Опирайся только на приведённые данные. Не добавляй цифры, "
        "которых нет в таблице. Отметь основную закономерность и наиболее "
        "заметные отклонения."
    )


def today_iso() -> str:
    """Текущая дата в виде строки."""
    return date.today().isoformat()
